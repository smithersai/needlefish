//! `zig build kzg-lines > src/common/crypto/kzg/prepared_lines.zig`: writes the KZG
//! verifier's precomputed Miller loop lines, `bls12_381.pairing.prepare` of the G2
//! generator and of [tau]G2 (verify.zig), as the Montgomery limbs `verify.prepared` reads.
//! With `--check <file>` it writes nothing and fails when the file differs from its output;
//! `zig build check` runs that against the committed file.

const std = @import("std");
const assert = std.debug.assert;
const base = @import("base");
const bls = base.common.crypto.bls12_381;
const verify = base.common.crypto.kzg.verify;

const command = "zig build kzg-lines > src/common/crypto/kzg/prepared_lines.zig";

const header =
    \\//! Generated by `zig build kzg-lines` (prepared_lines_main.zig); do not edit.
    \\//! Regenerate: `zig build kzg-lines > src/common/crypto/kzg/prepared_lines.zig`.
    \\//! `zig build check` fails while this file differs from that output.
    \\//!
    \\//! The Miller loop lines of the KZG verifier's two fixed G2 points (verify.zig):
    \\//! `bls12_381.pairing.prepare` of the G2 generator and of [tau]G2. Each point has
    \\//! `pairing.line_count` lines of three Fp2 coefficients; each coefficient is c0 then c1,
    \\//! each Fp its six little-endian 64-bit limbs in Montgomery form. The test "kzg verify:
    \\//! comptime prepared lines match runtime preparation" recomputes both and compares.
    \\
;

/// Limbs per output row: an Fp takes two rows.
const row_limbs = 3;

pub fn main(init: std.process.Init) !u8 {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    var generated: std.Io.Writer.Allocating = .init(init.gpa);
    defer generated.deinit();
    try generated.writer.writeAll(header);
    try write_point(&generated.writer, "generator", &bls.pairing.prepare(bls.g2.generator));
    try write_point(&generated.writer, "tau", &bls.pairing.prepare(verify.tau_g2));
    if (args.len == 3 and std.mem.eql(u8, args[1], "--check")) {
        return check(init.io, init.gpa, args[2], generated.written());
    }
    if (args.len != 1) {
        std.debug.print("usage: kzg-lines [--check <prepared_lines.zig>]\n", .{});
        return 2;
    }
    var buffer: [64 * 1024]u8 = undefined;
    var stdout = std.Io.File.stdout().writer(init.io, &buffer);
    try stdout.interface.writeAll(generated.written());
    try stdout.interface.flush();
    return 0;
}

/// 0 when the file at `path` holds exactly `generated`, else 1 with a message.
fn check(io: std.Io, gpa: std.mem.Allocator, path: []const u8, generated: []const u8) !u8 {
    assert(generated.len > header.len);
    const committed = try std.Io.Dir.cwd().readFileAlloc(io, path, gpa, .limited(1 << 20));
    defer gpa.free(committed);
    if (std.mem.eql(u8, committed, generated)) return 0;
    std.debug.print("{s} differs from the output of its generator; run:\n  {s}\n", .{
        path, command,
    });
    return 1;
}

fn write_point(
    out: *std.Io.Writer,
    name: []const u8,
    point: *const bls.pairing.PreparedG2,
) std.Io.Writer.Error!void {
    comptime assert(bls.Fp.limbs % row_limbs == 0);
    assert(!point.infinity);
    try out.print("\npub const {s} = [_]u64{{\n", .{name});
    var written: u32 = 0;
    for (point.lines) |line| {
        for (line) |coefficient| {
            for ([2]bls.Fp{ coefficient.c0, coefficient.c1 }) |element| {
                for (0..bls.Fp.limbs / row_limbs) |row| {
                    const limbs = element.limbs_value[row * row_limbs ..][0..row_limbs];
                    try out.print("    0x{x:0>16}, 0x{x:0>16}, 0x{x:0>16},\n", .{
                        limbs[0], limbs[1], limbs[2],
                    });
                    written += row_limbs;
                }
            }
        }
    }
    assert(written == verify.point_limbs);
    try out.writeAll("};\n");
}
