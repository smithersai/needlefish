//! `zig build secp-tables > src/common/crypto/secp256k1/table_data.zig`: writes the
//! secp256k1 generator tables from their `comptime_int` definitions (`table.computed`),
//! as the coordinates `table.zig` reads. With `--check <file>` it writes nothing and fails
//! when the file differs from its output; `zig build check` runs that against the committed
//! file.

const std = @import("std");
const assert = std.debug.assert;
const base = @import("base");
const table = base.common.crypto.secp256k1.table;

const command = "zig build secp-tables > src/common/crypto/secp256k1/table_data.zig";

const header =
    \\//! Generated by `zig build secp-tables` (table_main.zig); do not edit.
    \\//! Regenerate: `zig build secp-tables > src/common/crypto/secp256k1/table_data.zig`.
    \\//! `zig build check` fails while this file differs from that output.
    \\//!
    \\//! The secp256k1 generator tables of table.zig, as computed by its `comptime_int`
    \\//! definitions (`table.computed`): per point its x then its y, each the canonical
    \\//! integer below p; `gen_rows` row by row. The test "table: every entry equals its
    \\//! comptime_int definition" compares every entry with `table.computed`.
    \\
;

pub fn main(init: std.process.Init) !u8 {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    var generated: std.Io.Writer.Allocating = .init(init.gpa);
    defer generated.deinit();
    try write_file(&generated.writer);
    if (args.len == 3 and std.mem.eql(u8, args[1], "--check")) {
        return check(init.io, init.gpa, args[2], generated.written());
    }
    if (args.len != 1) {
        std.debug.print("usage: secp-tables [--check <table_data.zig>]\n", .{});
        return 2;
    }
    var buffer: [64 * 1024]u8 = undefined;
    var stdout = std.Io.File.stdout().writer(init.io, &buffer);
    try stdout.interface.writeAll(generated.written());
    try stdout.interface.flush();
    return 0;
}

/// 0 when the file at `path` holds exactly `generated`, else 1 with a message.
fn check(io: std.Io, gpa: std.mem.Allocator, path: []const u8, generated: []const u8) !u8 {
    assert(generated.len > header.len);
    const committed = try std.Io.Dir.cwd().readFileAlloc(io, path, gpa, .limited(1 << 20));
    defer gpa.free(committed);
    if (std.mem.eql(u8, committed, generated)) return 0;
    std.debug.print("{s} differs from the output of its generator; run:\n  {s}\n", .{
        path, command,
    });
    return 1;
}

fn write_file(out: *std.Io.Writer) std.Io.Writer.Error!void {
    try out.writeAll(header);
    try out.writeAll("\npub const g_odd = [_]u256{\n");
    try write_points(out, &table.computed.g_odd);
    try out.writeAll("};\n\npub const g_lambda_odd = [_]u256{\n");
    try write_points(out, &table.computed.g_lambda_odd);
    try out.writeAll("};\n\npub const gen_rows = [_]u256{\n");
    for (&table.computed.gen_rows) |*row| try write_points(out, row);
    try out.writeAll("};\n");
}

fn write_points(out: *std.Io.Writer, points: []const table.Affine) std.Io.Writer.Error!void {
    assert(points.len > 0);
    assert(points.len <= table.g_table_size);
    for (points) |point| {
        const x = point.x.to_int();
        const y = point.y.to_int();
        try out.print("    0x{x:0>64},\n    0x{x:0>64},\n", .{ x, y });
    }
}
