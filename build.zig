//! needlefish build graph.
//!
//! Layout mirrors base/base: `src/` holds the libraries, grouped like base/base's `crates/`,
//! and `bin/<name>/main.zig` holds binaries. Every package (a folder two levels under `src/`,
//! defined in etc/scripts/packages.py) is its own Zig module. `packages.zon` lists each
//! package and the packages it imports by name; the compiler rejects any other import.
//! `base` (src/base.zig) re-exports every group for binaries and tools.
//!
//! Steps:
//!   zig build              install every binary into zig-out/bin
//!   zig build test         run all unit tests, one binary per package (-Dtest-filter=...);
//!                          a slow binary runs as parallel shards (`test_shards`)
//!   zig build test:common/rlp  run one package's tests (reruns only when its inputs change)
//!   zig build fuzz         build fuzz smoke tests (use `zig build test --fuzz`)
//!   zig build sim -- SEED  run the deterministic simulator (DST) for SEED
//!   zig build bench        run micro benchmarks (ReleaseFast recommended)
//!   zig build -Ddiff-coverage  instrument `base diff-adapter` for coverage-guided fuzzing

const std = @import("std");

/// Every binary lives at `bin/<name>/main.zig`. Add new ones here.
const binaries = [_][]const u8{
    "base",
    "witness-diff",
    "replay-roots",
};

/// One row of packages.zon (generated by `etc/scripts/packages.py convert`).
const Package = struct {
    name: []const u8,
    /// Root source file; `src/<name>/root.zig` when null.
    root: ?[]const u8 = null,
    /// Packages, and `build_options`, that the package's files import by name.
    deps: []const []const u8,
};

const packages: []const Package = @import("packages.zon");

/// A package whose test binary runs too long on one core, and how many shards it runs as.
const Shards = struct { package: []const u8, count: u32 };

/// The only place shard counts live. Each package here compiles its test binary once and runs
/// it `count` times in parallel; each run executes the tests whose name hashes to its shard
/// (src/testing/test_runner.zig), so the run costs its slowest shard, not the sum. Every
/// other package runs its binary once with Zig's default runner. A count is the smallest, up to
/// 16, whose slowest shard is within 5% of the package's slowest test (per-test CPU seconds),
/// else the count up to 16 with the shortest slowest shard: no count makes a run shorter than
/// its slowest test.
const test_shards = [_]Shards{
    .{ .package = "batcher/blobs", .count = 4 },
    .{ .package = "batcher/devnet", .count = 3 },
    .{ .package = "batcher/txmgr", .count = 4 },
    .{ .package = "common/crypto", .count = 16 },
    .{ .package = "consensus/p2p", .count = 10 },
    .{ .package = "execution/db", .count = 9 },
    .{ .package = "execution/import", .count = 14 },
    .{ .package = "execution/node", .count = 13 },
    .{ .package = "execution/trie", .count = 7 },
    .{ .package = "infra/replay", .count = 7 },
    .{ .package = "proof", .count = 4 },
    .{ .package = "proof/tee", .count = 4 },
    .{ .package = "testing", .count = 10 },
    .{ .package = "testing/sim", .count = 9 },
};

fn shard_count(package: []const u8) u32 {
    for (test_shards) |shards| {
        if (std.mem.eql(u8, shards.package, package)) return shards.count;
    }
    return 1;
}

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});
    const test_filter = b.option([]const u8, "test-filter", "Only run tests matching");

    const configured = build_options(b);
    const modules = add_packages(b, configured, target, optimize);
    const base = modules[package_index("base")];

    // Unit tests: one test binary per package; Zig runs only the root module's tests.
    const filters: []const []const u8 = if (test_filter) |f| &.{f} else &.{};
    const test_step = b.step("test", "Run unit tests");
    // Compile-only check for editors and CI speed.
    const check_step = b.step("check", "Compile everything without running");
    add_package_tests(b, modules, filters, test_step, check_step);

    // The edge counters (`-ffuzz`) need the LLVM backend and linker.
    const use_llvm: ?bool = if (configured.diff_coverage) true else null;
    add_binaries(b, base, target, optimize, test_step, filters, use_llvm);

    // Deterministic simulation testing and micro benchmarks.
    const sim = add_tool(b, base, target, optimize, .{
        .name = "simulator",
        .path = "src/testing/simulator_main.zig",
        .step = "sim",
        .description = "Run the deterministic simulator: zig build sim -- [seed]",
    });
    b.installArtifact(sim);
    const bench = add_tool(b, base, target, optimize, .{
        .name = "bench",
        .path = "src/testing/bench_main.zig",
        .step = "bench",
        .description = "Run micro benchmarks",
    });

    const statetest = add_vector_tools(b, base, target, optimize);
    // `etc/bench/evm2.sh` installs the state-test runner (`statetest --bench`) per build mode.
    const bench_tools = b.step("bench-tools", "Install the benchmark tools (statetest)");
    bench_tools.dependOn(&b.addInstallArtifact(statetest, .{}).step);
    // Compile (not run) the state-test runner on every `zig build test`: it is the EVM's
    // conformance oracle, and cross-lane API changes once broke it unnoticed.
    test_step.dependOn(&statetest.step);

    check_step.dependOn(&sim.step);
    check_step.dependOn(&bench.step);
    check_step.dependOn(&statetest.step);
}

const Configured = struct { options: *std.Build.Step.Options, diff_coverage: bool };

/// Build options shared by every compilation (`build_options`).
fn build_options(b: *std.Build) Configured {
    const options = b.addOptions();
    options.addOption([]const u8, "version", "0.0.0");
    const git_rev = b.option([]const u8, "git-rev", "Git revision baked into binaries");
    options.addOption([]const u8, "git_rev", git_rev orelse "unknown");
    const slow_tests = b.option(bool, "slow-tests", "Also run large simulation tests") orelse false;
    options.addOption(bool, "slow_tests", slow_tests);
    const require_io_uring = b.option(
        bool,
        "require-io-uring",
        "Fail (instead of skip) OS IO tests when io_uring is unavailable",
    ) orelse false;
    options.addOption(bool, "require_io_uring", require_io_uring);
    const fuzz_soak = b.option(u32, "fuzz-soak", "Multiply seeded fuzz iterations") orelse 1;
    options.addOption(u32, "fuzz_soak", fuzz_soak);
    const fuzz_seed = b.option(u64, "fuzz-seed", "Mixed into every seeded fuzz seed") orelse 0;
    options.addOption(u64, "fuzz_seed", fuzz_seed);
    const opcode_profile = b.option(bool, "evm-opcode-profile", "Time EVM opcodes") orelse false;
    options.addOption(bool, "evm_opcode_profile", opcode_profile);
    // `base diff-adapter` coverage (BASE_DIFF_COVERAGE): semantic hooks plus the compiler's
    // edge counters on every package module (`-ffuzz` instrumentation).
    const diff_coverage = b.option(bool, "diff-coverage", "Diff-adapter coverage") orelse false;
    options.addOption(bool, "diff_coverage", diff_coverage);

    return .{ .options = options, .diff_coverage = diff_coverage };
}

/// One module per row of packages.zon, wired to the modules its files import by name.
fn add_packages(
    b: *std.Build,
    configured: Configured,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) []*std.Build.Module {
    const modules = b.allocator.alloc(*std.Build.Module, packages.len) catch @panic("OOM");
    for (packages, modules) |package, *module| {
        const root = package.root orelse b.fmt("src/{s}/root.zig", .{package.name});
        module.* = b.addModule(package.name, .{
            .root_source_file = b.path(root),
            .target = target,
            .optimize = optimize,
            .fuzz = if (configured.diff_coverage) true else null,
        });
    }
    // One `build_options` module: a file may belong to only one module per compilation.
    const options_module = configured.options.createModule();
    for (packages, modules) |package, module| {
        for (package.deps) |dep| {
            if (std.mem.eql(u8, dep, "build_options")) {
                module.addImport(dep, options_module);
            } else {
                module.addImport(dep, modules[package_index(dep)]);
            }
        }
    }
    return modules;
}

fn package_index(name: []const u8) usize {
    for (packages, 0..) |package, index| {
        if (std.mem.eql(u8, package.name, name)) return index;
    }
    std.debug.panic("packages.zon has no package named '{s}'", .{name});
}

/// One test binary per package, named after the package with `/` as `-`, and a
/// `test:<package>` step that runs only it: `zig build test:common/rlp`.
fn add_package_tests(
    b: *std.Build,
    modules: []const *std.Build.Module,
    filters: []const []const u8,
    test_step: *std.Build.Step,
    check_step: *std.Build.Step,
) void {
    std.debug.assert(modules.len == packages.len);
    for (test_shards) |shards| {
        std.debug.assert(shards.count >= 2);
        _ = package_index(shards.package);
    }
    // etc/scripts/test-times.sh runs each installed binary to time its tests.
    const install_step = b.step("test-bins", "Install every package's test binary in zig-out/test");
    for (packages, modules) |package, module| {
        const name = b.allocator.dupe(u8, package.name) catch @panic("OOM");
        std.mem.replaceScalar(u8, name, '/', '-');
        const shards = shard_count(package.name);
        const unit_tests = b.addTest(.{
            .name = name,
            .root_module = module,
            .filters = filters,
            .test_runner = if (shards == 1) null else .{
                .path = b.path("src/testing/test_runner.zig"),
                .mode = .server,
            },
        });
        const description = b.fmt("Run the {s} package's tests", .{package.name});
        const package_step = b.step(b.fmt("test:{s}", .{package.name}), description);
        for (0..shards) |shard| {
            const run_tests = b.addRunArtifact(unit_tests);
            if (shards > 1) {
                run_tests.setName(b.fmt("run test {s} shard {d}/{d}", .{ name, shard, shards }));
                run_tests.addArg(b.fmt("--shard={d}/{d}", .{ shard, shards }));
            }
            test_step.dependOn(&run_tests.step);
            package_step.dependOn(&run_tests.step);
        }
        check_step.dependOn(&unit_tests.step);
        install_step.dependOn(&b.addInstallArtifact(unit_tests, .{
            .dest_dir = .{ .override = .{ .custom = "test" } },
        }).step);
    }
}

/// Runners over public vectors fetched by `just vectors`.
fn add_vector_tools(
    b: *std.Build,
    base: *std.Build.Module,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Step.Compile {
    // ethereum/tests GeneralStateTests runner (vectors from `just vectors`).
    const statetest = add_tool(b, base, target, optimize, .{
        .name = "statetest",
        .path = "src/execution/evm/state_test_main.zig",
        .step = "statetest",
        .description = "Run state tests: zig build statetest -- <file-or-dir>",
    });

    // Real chain blocks, one transaction at a time on its prestateTracer pre-state.
    _ = add_tool(b, base, target, optimize, .{
        .name = "txcheck",
        .path = "src/execution/evm/tx_check_main.zig",
        .step = "txcheck",
        .description = "Check txs against receipts: zig build txcheck -- <block-dir>...",
    });

    // ethereum/tests TransactionTests through the strict tx decoder.
    _ = add_tool(b, base, target, optimize, .{
        .name = "txtest",
        .path = "src/common/consensus/tx_test_main.zig",
        .step = "txtest",
        .description = "Run transaction tests: zig build txtest -- <file-or-dir>",
    });

    // ethereum/tests BlockchainTests block RLP through the strict block decoder.
    _ = add_tool(b, base, target, optimize, .{
        .name = "blockrlp",
        .path = "src/common/consensus/block_test_main.zig",
        .step = "blockrlp",
        .description = "Check block RLP: zig build blockrlp -- <file-or-dir>",
    });

    // base/base genesis parity (files from `just vectors`).
    _ = add_tool(b, base, target, optimize, .{
        .name = "genesischeck",
        .path = "src/common/genesis/check_main.zig",
        .step = "genesischeck",
        .description = "Check genesis files: zig build genesischeck -- <genesis.json>...",
    });
    return statetest;
}

const Tool = struct {
    name: []const u8,
    path: []const u8,
    step: []const u8,
    description: []const u8,
};

/// An executable over the `base` module with a run step that forwards `-- args`.
fn add_tool(
    b: *std.Build,
    base: *std.Build.Module,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    tool: Tool,
) *std.Build.Step.Compile {
    const exe = b.addExecutable(.{
        .name = tool.name,
        .root_module = b.createModule(.{
            .root_source_file = b.path(tool.path),
            .target = target,
            .optimize = optimize,
            .imports = &.{.{ .name = "base", .module = base }},
        }),
    });
    const run = b.addRunArtifact(exe);
    run.addPassthruArgs();
    b.step(tool.step, tool.description).dependOn(&run.step);
    return exe;
}

/// Each binary gets an install, a `run-<name>` step, and its own test binary.
fn add_binaries(
    b: *std.Build,
    base: *std.Build.Module,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    test_step: *std.Build.Step,
    filters: []const []const u8,
    use_llvm: ?bool,
) void {
    for (binaries) |name| {
        const exe = b.addExecutable(.{
            .name = name,
            .use_llvm = use_llvm,
            .root_module = b.createModule(.{
                .root_source_file = b.path(b.fmt("bin/{s}/main.zig", .{name})),
                .target = target,
                .optimize = optimize,
                .imports = &.{.{ .name = "base", .module = base }},
            }),
        });
        b.installArtifact(exe);

        const run = b.addRunArtifact(exe);
        run.addPassthruArgs();
        const run_step = b.step(b.fmt("run-{s}", .{name}), b.fmt("Run {s}", .{name}));
        run_step.dependOn(&run.step);
        if (std.mem.eql(u8, name, "replay-roots")) {
            b.step(name, "Check state/receipts/transactions roots: replay-roots -- DIR [BLOCK]")
                .dependOn(&run.step);
        }
    }

    // Binary tests (each main.zig may hold integration tests).
    for (binaries) |name| {
        const bin_tests = b.addTest(.{
            .name = b.fmt("test-{s}", .{name}),
            .root_module = b.createModule(.{
                .root_source_file = b.path(b.fmt("bin/{s}/main.zig", .{name})),
                .target = target,
                .optimize = optimize,
                .imports = &.{.{ .name = "base", .module = base }},
            }),
            .filters = filters,
        });
        test_step.dependOn(&b.addRunArtifact(bin_tests).step);
    }
}
