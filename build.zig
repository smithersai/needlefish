//! needlefish build graph.
//!
//! Layout mirrors base/base: `src/` holds the libraries, grouped like base/base's `crates/`,
//! and `bin/<name>/main.zig` holds binaries. Every package (a folder two levels under `src/`,
//! and each file of a binary, defined in etc/scripts/packages.py) is its own Zig module.
//! `packages.zon` lists each package and the packages it imports by name; the compiler
//! rejects any other import. `base` (src/base.zig) re-exports every group for tools.
//!
//! Steps:
//!   zig build              install every binary into zig-out/bin
//!   zig build test         run all unit tests, one binary per package (-Dtest-filter=...);
//!                          a slow binary runs as parallel shards (`test_shards`;
//!                          -Dtest-shards=false runs every binary once, with Zig's runner)
//!   zig build check        compile every test binary and tool without running them
//!   zig build test:common/rlp  run one package's tests (reruns only when its inputs change)
//!   zig build check:common/rlp compile one package's test binary without running it
//!   zig build test:common/crypto@2/4  run the second quarter of a sharded package's shards
//!                          (`test_group_counts`), so CI jobs can share one package
//!   `test` and `check` depend only on named steps (`ci_steps`), so CI can run them in parts
//!   -Dtest-debug-info      Debug test binaries keep their debug info (see `test_root_module`):
//!                          a failing test then prints file:line and its stack and error
//!                          return trace, and each binary compiles about twice as slowly
//!   zig build fuzz         build fuzz smoke tests (fuzz: `zig build test --fuzz
//!                          -Dtest-shards=false`; our test runner never fuzzes)
//!   zig build sim -- SEED  run the deterministic simulator (DST) for SEED
//!   zig build bench        run micro benchmarks (ReleaseFast recommended)
//!   zig build -Ddiff-coverage  instrument `base diff-adapter` for coverage-guided fuzzing

const std = @import("std");

/// Every binary lives at `bin/<name>/main.zig`. Add new ones here.
const binaries = [_][]const u8{
    "base",
    "witness-diff",
    "replay-roots",
};

/// One row of packages.zon (generated by `etc/scripts/packages.py convert`).
const Package = struct {
    name: []const u8,
    /// Root source file; `src/<name>/root.zig` when null.
    root: ?[]const u8 = null,
    /// Packages, and `build_options`, that the package's files import by name.
    deps: []const []const u8,
    /// Its tests only reference declarations: `zig build check` compiles its test binary and
    /// `zig build test` does not run it (`zig build test:<name>` still does).
    compile_only: bool = false,
};

const packages: []const Package = @import("packages.zon");

/// A package whose test binary runs too long on one core, and how many shards it runs as.
const Shards = struct { package: []const u8, count: u32 };

/// The only place shard counts live. Each package here compiles its test binary once and runs
/// it `count` times in parallel; each run executes the tests whose name hashes to its shard
/// (src/testing/test_runner.zig), so the run costs its slowest shard, not the sum. Every
/// other package runs its binary once, with the same runner and no `--shard`. A count is the
/// smallest, up to 16, whose slowest shard is within 5% of the package's slowest test
/// (per-test CPU seconds), else the count up to 16 with the shortest slowest shard: no count
/// makes a run shorter than its slowest test.
const test_shards = [_]Shards{
    .{ .package = "batcher/devnet", .count = 3 },
    .{ .package = "common/crypto", .count = 16 },
    .{ .package = "consensus/p2p", .count = 10 },
    .{ .package = "execution/db", .count = 15 },
    .{ .package = "execution/import", .count = 14 },
    .{ .package = "execution/node", .count = 13 },
    .{ .package = "execution/trie", .count = 7 },
    .{ .package = "infra/follow", .count = 2 },
    .{ .package = "infra/replay", .count = 7 },
    .{ .package = "proof", .count = 14 },
    .{ .package = "proof/tee", .count = 12 },
    .{ .package = "testing", .count = 10 },
    .{ .package = "testing/sim", .count = 16 },
};

/// The group counts a sharded package's runs also come in, so that several CI jobs can share
/// one package (etc/scripts/ci-shards.py reads this list). For each count G up to the
/// package's shard count N, `test:<package>@K/G` (K from 1 to G) runs the shards from
/// (K-1)*N/G to K*N/G - 1: the groups of one G run every shard of `test:<package>` exactly
/// once (`assert_groups_partition`). Each job that runs a group compiles the binary itself.
const test_group_counts = [_]u32{ 2, 3, 4 };

/// Packages whose test binary LLVM compiles on every target, because Zig's own backend, the
/// Debug default on x86_64 Linux, emits code that runs their tests slower by more than LLVM's
/// longer compile costs. That changes x86_64 Linux only. Every other test binary keeps the
/// default backend, which compiles three to five times faster; for most packages its code runs
/// the tests about as fast as LLVM's.
const llvm_test_packages = [_][]const u8{
    "batcher/devnet",
    "common/crypto",
    "consensus/p2p",
    "execution/trie",
    "infra/follow",
    "proof/tee",
    "testing",
    "testing/sim",
};

fn llvm_test(package: []const u8) bool {
    for (llvm_test_packages) |name| {
        if (std.mem.eql(u8, name, package)) return true;
    }
    return false;
}

fn shard_count(package: []const u8) u32 {
    for (test_shards) |shards| {
        if (std.mem.eql(u8, shards.package, package)) return shards.count;
    }
    return 1;
}

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});
    const test_filter = b.option([]const u8, "test-filter", "Only run tests matching");

    const configured = build_options(b);
    const modules = add_packages(b, configured, target, optimize);
    const base = modules[package_index("base")];

    // Unit tests: one test binary per package; Zig runs only the root module's tests.
    const filters: []const []const u8 = if (test_filter) |f| &.{f} else &.{};
    const test_step = b.step("test", "Run unit tests");
    // Compile-only check for editors and CI speed.
    const check_step = b.step("check", "Compile everything without running");
    add_package_tests(b, modules, filters, configured, test_step, check_step);

    // The edge counters (`-ffuzz`) need the LLVM backend and linker.
    const use_llvm: ?bool = if (configured.diff_coverage) true else null;
    add_binaries(b, modules, use_llvm);

    // Deterministic simulation testing and micro benchmarks.
    const uses_base: []const std.Build.Module.Import = &.{.{ .name = "base", .module = base }};
    const sim = add_tool(b, uses_base, target, optimize, .{
        .name = "simulator",
        .path = "src/testing/simulator_main.zig",
        .step = "sim",
        .description = "Run the deterministic simulator: zig build sim -- [seed]",
    });
    b.installArtifact(sim);
    const bench = add_tool(b, uses_base, target, optimize, .{
        .name = "bench",
        .path = "src/testing/bench_main.zig",
        .step = "bench",
        .description = "Run micro benchmarks",
    });

    const statetest = add_vector_tools(b, modules, target, optimize);
    // `etc/bench/evm2.sh` installs the state-test runner (`statetest --bench`) per build mode.
    const bench_tools = b.step("bench-tools", "Install the benchmark tools (statetest)");
    bench_tools.dependOn(&b.addInstallArtifact(statetest, .{}).step);
    // Compile (not run) the state-test runner in `zig build test`: it is the EVM's conformance
    // oracle, and cross-lane API changes once broke it unnoticed. It imports only the EVM, so
    // it recompiles only when a file the EVM compiles changes.
    const statetest_step = b.step("test:statetest", "Compile the state-test runner");
    statetest_step.dependOn(&statetest.step);
    test_step.dependOn(statetest_step);

    b.step("check:simulator", "Compile the simulator").dependOn(&sim.step);
    b.step("check:bench", "Compile the micro benchmarks").dependOn(&bench.step);
    // Generated tables: each generator gets a step that prints its file, and
    // `zig build check` runs it against the committed output.
    add_generators(b, uses_base, target, optimize);
    check_step.dependOn(statetest_step);
    for (ci_steps) |name| {
        if (std.mem.startsWith(u8, name, "check:")) check_step.dependOn(top_level_step(b, name));
    }
    assert_named_dependencies(test_step, "test:");
    assert_named_dependencies(check_step, "check:");
    assert_checks_covered(b, check_step);
}

/// The named steps `zig build test` and `zig build check` depend on besides each package's
/// `test:<package>` and `check:<package>`. CI runs `just ci` as these named steps, split across
/// parallel jobs (etc/scripts/ci-shards.py reads this list); `assert_named_dependencies` fails
/// the build when `test` or `check` depends directly on any other step. CI runs a running
/// package's `test:<package>` in place of its `check:<package>`, and `assert_checks_covered`
/// fails the build when that `check:<package>` holds more than the compile `test:` runs.
const ci_steps = [_][]const u8{
    "test:statetest",
    "check:simulator",
    "check:bench",
    "check:kzg-lines",
    "check:secp-tables",
};

fn top_level_step(b: *std.Build, name: []const u8) *std.Build.Step {
    const top_level = b.top_level_steps.get(name) orelse
        std.debug.panic("build.zig declares no step named '{s}'", .{name});
    std.debug.assert(std.mem.eql(u8, top_level.step.name, name));
    return &top_level.step;
}

/// Each dependency of `step` is a top-level step named in `ci_steps` or `<prefix><package>`
/// (for `test:`, a package `zig build test` runs), so CI can run `step` as its named parts.
fn assert_named_dependencies(step: *std.Build.Step, prefix: []const u8) void {
    std.debug.assert(step.dependencies.items.len > 0);
    for (step.dependencies.items) |dependency| {
        const name = dependency.name;
        const listed = for (ci_steps) |ci_step| {
            if (std.mem.eql(u8, ci_step, name)) break true;
        } else false;
        if (dependency.tag != .top_level or !(listed or package_step(name, prefix))) {
            std.debug.panic("'{s}' depends on '{s}', which is not a named step in ci_steps " ++
                "or {s}<package> (build.zig)", .{ step.name, name, prefix });
        }
    }
}

/// Each `check:<package>` of a package `zig build test` runs depends on nothing but one compile
/// step, and every direct dependency of `test:<package>` lists that compile step among its own
/// direct dependencies. So running `test:<package>` builds everything `check:<package>` builds,
/// and CI, which runs the first in place of the second, skips nothing.
fn assert_checks_covered(b: *std.Build, check_step: *std.Build.Step) void {
    for (check_step.dependencies.items) |check| {
        if (!std.mem.startsWith(u8, check.name, "check:")) continue;
        const test_name = b.fmt("test:{s}", .{check.name["check:".len..]});
        if (!package_step(test_name, "test:")) continue;
        const compile = check.dependencies.items;
        if (compile.len != 1 or compile[0].tag != .compile) {
            std.debug.panic("'{s}' must depend only on its test binary's compile: CI runs " ++
                "'{s}' in its place", .{ check.name, test_name });
        }
        const runs = top_level_step(b, test_name).dependencies.items;
        std.debug.assert(runs.len > 0);
        for (runs) |run| {
            const runs_binary = for (run.dependencies.items) |dependency| {
                if (dependency == compile[0]) break true;
            } else false;
            if (!runs_binary) std.debug.panic("'{s}' has a step that does not depend on " ++
                "the compile '{s}' holds", .{ test_name, check.name });
        }
    }
}

/// `name` is `<prefix><package>`; for `test:`, of a package that `zig build test` runs.
fn package_step(name: []const u8, prefix: []const u8) bool {
    std.debug.assert(prefix.len > 0);
    if (!std.mem.startsWith(u8, name, prefix)) return false;
    const runs = std.mem.eql(u8, prefix, "test:");
    for (packages) |package| {
        if (!std.mem.eql(u8, package.name, name[prefix.len..])) continue;
        return !(runs and package.compile_only);
    }
    return false;
}

const Configured = struct {
    options: *std.Build.Step.Options,
    diff_coverage: bool,
    /// Packages in `test_shards` run as shards and every test binary uses
    /// src/testing/test_runner.zig; false runs every test binary once with Zig's runner.
    test_shards: bool,
    /// Debug test binaries keep their debug info (`test_root_module`).
    test_debug_info: bool,
};

/// Build options shared by every compilation (`build_options`).
fn build_options(b: *std.Build) Configured {
    const options = b.addOptions();
    options.addOption([]const u8, "version", "0.0.0");
    const git_rev = b.option([]const u8, "git-rev", "Git revision baked into binaries");
    options.addOption([]const u8, "git_rev", git_rev orelse "unknown");
    const slow_tests = b.option(bool, "slow-tests", "Also run large simulation tests") orelse false;
    options.addOption(bool, "slow_tests", slow_tests);
    const require_io_uring = b.option(
        bool,
        "require-io-uring",
        "Fail (instead of skip) OS IO tests when io_uring is unavailable",
    ) orelse false;
    options.addOption(bool, "require_io_uring", require_io_uring);
    const fuzz_soak = b.option(u32, "fuzz-soak", "Multiply seeded fuzz iterations") orelse 1;
    options.addOption(u32, "fuzz_soak", fuzz_soak);
    const fuzz_seed = b.option(u64, "fuzz-seed", "Mixed into every seeded fuzz seed") orelse 0;
    options.addOption(u64, "fuzz_seed", fuzz_seed);
    const opcode_profile = b.option(bool, "evm-opcode-profile", "Time EVM opcodes") orelse false;
    options.addOption(bool, "evm_opcode_profile", opcode_profile);
    // `base diff-adapter` coverage (BASE_DIFF_COVERAGE): semantic hooks plus the compiler's
    // edge counters on every package module (`-ffuzz` instrumentation).
    const diff_coverage = b.option(bool, "diff-coverage", "Diff-adapter coverage") orelse false;
    options.addOption(bool, "diff_coverage", diff_coverage);

    // Zig's build runner keeps fuzzing state per run step, and `build.zig` cannot see
    // `--fuzz`: every fuzz command passes -Dtest-shards=false (src/testing/test_runner.zig).
    // A fuzz-instrumented build (-Ddiff-coverage) never shards either.
    const shards_on = b.option(
        bool,
        "test-shards",
        "Run slow test binaries as parallel shards (default); false with --fuzz",
    ) orelse true;
    const test_debug_info = b.option(
        bool,
        "test-debug-info",
        "Keep debug info in Debug test binaries: file:line and traces of a failing test",
    ) orelse false;
    return .{
        .options = options,
        .diff_coverage = diff_coverage,
        .test_shards = shards_on and !diff_coverage,
        .test_debug_info = test_debug_info,
    };
}

/// One module per row of packages.zon, wired to the modules its files import by name.
fn add_packages(
    b: *std.Build,
    configured: Configured,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) []*std.Build.Module {
    const modules = b.allocator.alloc(*std.Build.Module, packages.len) catch @panic("OOM");
    for (packages, modules) |package, *module| {
        const root = package.root orelse b.fmt("src/{s}/root.zig", .{package.name});
        // A binary's own files (`bin/`) take no edge counters.
        const program = std.mem.startsWith(u8, package.name, "bin/");
        module.* = b.addModule(package.name, .{
            .root_source_file = b.path(root),
            .target = target,
            .optimize = optimize,
            .fuzz = if (configured.diff_coverage and !program) true else null,
        });
    }
    // One `build_options` module: a file may belong to only one module per compilation.
    const options_module = configured.options.createModule();
    for (packages, modules) |package, module| {
        for (package.deps) |dep| {
            if (std.mem.eql(u8, dep, "build_options")) {
                module.addImport(dep, options_module);
            } else {
                module.addImport(dep, modules[package_index(dep)]);
            }
        }
    }
    return modules;
}

fn package_index(name: []const u8) usize {
    for (packages, 0..) |package, index| {
        if (std.mem.eql(u8, package.name, name)) return index;
    }
    std.debug.panic("packages.zon has no package named '{s}'", .{name});
}

/// One test binary per package, named after the package with `/` as `-`, a `test:<package>`
/// step that runs only it (`zig build test:common/rlp`) and a `check:<package>` step that only
/// compiles it. `test` depends on the first unless the package is `compile_only`, and `check` on
/// the second. With `sharded`, every binary uses our test runner, which prints a failing test's
/// error even without debug info, and a package in `test_shards` runs its binary as that many
/// shards. Without it (fuzzing), every binary uses Zig's default runner.
fn add_package_tests(
    b: *std.Build,
    modules: []const *std.Build.Module,
    filters: []const []const u8,
    configured: Configured,
    test_step: *std.Build.Step,
    check_step: *std.Build.Step,
) void {
    const sharded = configured.test_shards;
    std.debug.assert(modules.len == packages.len);
    for (test_shards) |shards| {
        std.debug.assert(shards.count >= 2);
        std.debug.assert(!packages[package_index(shards.package)].compile_only);
    }
    // Each name is a package: package_index panics otherwise.
    for (llvm_test_packages) |name| std.debug.assert(!packages[package_index(name)].compile_only);
    for (optimized_test_packages) |name| _ = package_index(name);
    // etc/scripts/test-times.sh runs each installed binary to time its tests.
    const install_step = b.step("test-bins", "Install every package's test binary in zig-out/test");
    for (packages, modules) |package, module| {
        const name = b.allocator.dupe(u8, package.name) catch @panic("OOM");
        std.mem.replaceScalar(u8, name, '/', '-');
        const shards = if (sharded) shard_count(package.name) else 1;
        // Zig's own runner prints only a trace: its binaries keep their debug info.
        const debug_info = configured.test_debug_info or !sharded;
        const unit_tests = b.addTest(.{
            .name = name,
            .root_module = test_root_module(b, package.name, module, debug_info),
            .filters = filters,
            .use_llvm = if (llvm_test(package.name)) true else null,
            .test_runner = if (!sharded) null else .{
                .path = b.path("src/testing/test_runner.zig"),
                .mode = .server,
            },
        });
        const description = b.fmt("Run the {s} package's tests", .{package.name});
        const run_step = b.step(b.fmt("test:{s}", .{package.name}), description);
        for (0..shards) |shard| {
            const run_tests = b.addRunArtifact(unit_tests);
            if (shards > 1) {
                run_tests.setName(b.fmt("run test {s} shard {d}/{d}", .{ name, shard, shards }));
                run_tests.addArg(b.fmt("--shard={d}/{d}", .{ shard, shards }));
            }
            run_step.dependOn(&run_tests.step);
        }
        if (shards > 1) {
            add_test_groups(b, package.name, run_step);
            assert_groups_partition(b, package.name, run_step);
        }
        if (!package.compile_only) test_step.dependOn(run_step);
        const compile_description = b.fmt("Compile the {s} package's test binary", .{package.name});
        const compile_step = b.step(b.fmt("check:{s}", .{package.name}), compile_description);
        compile_step.dependOn(&unit_tests.step);
        check_step.dependOn(compile_step);
        install_step.dependOn(&b.addInstallArtifact(unit_tests, .{
            .dest_dir = .{ .override = .{ .custom = "test" } },
        }).step);
    }
}

/// `test:<package>@K/G` for each G of `test_group_counts` up to the package's shard count N:
/// group K depends on the run steps of `test:<package>` from (K-1)*N/G to K*N/G - 1.
fn add_test_groups(b: *std.Build, package_name: []const u8, run_step: *std.Build.Step) void {
    const runs = run_step.dependencies.items;
    const count: u32 = @intCast(runs.len);
    std.debug.assert(count >= 2);
    for (test_group_counts) |groups| {
        std.debug.assert(groups >= 2);
        if (groups > count) continue;
        var end_previous: u32 = 0;
        for (0..groups) |index| {
            const group: u32 = @intCast(index);
            const first = group * count / groups;
            const end = (group + 1) * count / groups;
            std.debug.assert(first == end_previous and end > first);
            const step = b.step(
                b.fmt("test:{s}@{d}/{d}", .{ package_name, group + 1, groups }),
                b.fmt("Run test shards {d} to {d} of {d} of the {s} package", .{
                    first, end - 1, count, package_name,
                }),
            );
            for (runs[first..end]) |run| step.dependOn(run);
            end_previous = end;
        }
        std.debug.assert(end_previous == count);
    }
}

/// For each G of `test_group_counts` up to the shard count, the groups `test:<package>@K/G`
/// depend on nothing but run steps of `test:<package>`, and on each of them exactly once
/// over all K: CI runs a package as its groups of one G, so this proves that every test still
/// runs, and runs once.
fn assert_groups_partition(
    b: *std.Build,
    package_name: []const u8,
    run_step: *std.Build.Step,
) void {
    const runs = run_step.dependencies.items;
    std.debug.assert(runs.len >= 2);
    for (test_group_counts) |groups| {
        if (groups > runs.len) continue;
        var held: usize = 0;
        for (runs) |run| {
            var times: u32 = 0;
            for (1..groups + 1) |group| {
                const name = b.fmt("test:{s}@{d}/{d}", .{ package_name, group, groups });
                const dependencies = top_level_step(b, name).dependencies.items;
                if (run == runs[0]) held += dependencies.len;
                for (dependencies) |dependency| times += @intFromBool(dependency == run);
            }
            if (times != 1) std.debug.panic("the groups 'test:{s}@K/{d}' run '{s}' {d} times, " ++
                "not once", .{ package_name, groups, run.name, times });
        }
        if (held != runs.len) std.debug.panic("the groups 'test:{s}@K/{d}' hold {d} steps, not " ++
            "the {d} runs of 'test:{s}'", .{ package_name, groups, held, runs.len, package_name });
    }
}

/// Packages whose test binary compiles ReleaseSafe even in a Debug build, because a test of
/// theirs is compute bound and the optimized compile costs less than the run saves. Only the
/// test binary's root module changes: no file of these packages reads `builtin.mode`, and
/// the modules they import keep theirs. ReleaseSafe keeps every safety check and assert.
/// The root module's mode is what optimizes a compilation: a ReleaseSafe common/crypto module
/// inside a Debug test binary runs no faster.
const optimized_test_packages = [_][]const u8{
    // KZG: "blobs: ..." and "txmgr: blob mode sends a 4844 tx committing to the frame ...".
    "batcher/blobs",
    "batcher/txmgr",
    // "digest table: matches a hash map across growth, clears, and a full table".
    "execution/digest_table",
    // "driver: blob sends carry a v1 (cell proof) sidecar": an FK20 setup and 128 KZG proofs.
    "infra/tx_manager",
};

/// The root module of a package's test binary. In a Debug build it is a copy of the package's
/// module with the same imports, so programs and tools keep their settings, and the copy is
/// ReleaseSafe for a package in `optimized_test_packages`. Unless `debug_info`, the copy is
/// stripped; the modules it imports set no `strip` and inherit it, so the binary, std
/// included, has no DWARF. That halves the LLVM compile of a heavy test binary. A failing
/// test still prints its name, its error (src/testing/test_runner.zig), a panic's message and
/// `expectEqual`'s values, but no file:line, stack trace or error return trace: rerun its
/// package with `-Dtest-debug-info=true`. Stripping only the imported modules would keep the
/// package's own lines, but Zig 0.17.1's LLVM backend crashes when a stripped module calls
/// std's `inline fn readInt`. Other builds, such as fuzzing's ReleaseSafe, use the module.
/// The caller asks for `debug_info` whenever Zig's own runner runs the binary.
fn test_root_module(
    b: *std.Build,
    package_name: []const u8,
    module: *std.Build.Module,
    debug_info: bool,
) *std.Build.Module {
    if (module.optimize.? != .debug) return module;
    const optimized = for (optimized_test_packages) |optimized_name| {
        if (std.mem.eql(u8, optimized_name, package_name)) break true;
    } else false;
    const copy = b.createModule(.{
        .root_source_file = module.root_source_file,
        .target = module.resolved_target,
        .optimize = if (optimized) .safe else .debug,
        .fuzz = module.fuzz,
        .strip = if (debug_info) null else true,
    });
    std.debug.assert(module.strip == null);
    var imports = module.import_table.iterator();
    while (imports.next()) |entry| copy.addImport(entry.key_ptr.*, entry.value_ptr.*);
    std.debug.assert(copy.import_table.count() == module.import_table.count());
    return copy;
}

/// Runners over public vectors fetched by `just vectors`.
fn add_vector_tools(
    b: *std.Build,
    modules: []const *std.Build.Module,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Step.Compile {
    const uses_base: []const std.Build.Module.Import = &.{
        .{ .name = "base", .module = modules[package_index("base")] },
    };
    // ethereum/tests GeneralStateTests runner (vectors from `just vectors`). It imports only
    // the EVM, so an edit outside the EVM's packages does not recompile it.
    const uses_evm: []const std.Build.Module.Import = &.{
        .{ .name = "execution/evm", .module = modules[package_index("execution/evm")] },
