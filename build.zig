    const statetest = add_tool(b, uses_evm, target, optimize, .{
        .name = "statetest",
        .path = "src/execution/evm/state_test_main.zig",
        .step = "statetest",
        .description = "Run state tests: zig build statetest -- <file-or-dir>",
    });

    // Real chain blocks, one transaction at a time on its prestateTracer pre-state.
    _ = add_tool(b, uses_base, target, optimize, .{
        .name = "txcheck",
        .path = "src/execution/evm/tx_check_main.zig",
        .step = "txcheck",
        .description = "Check txs against receipts: zig build txcheck -- <block-dir>...",
    });

    // ethereum/tests TransactionTests through the strict tx decoder.
    _ = add_tool(b, uses_base, target, optimize, .{
        .name = "txtest",
        .path = "src/common/consensus/tx_test_main.zig",
        .step = "txtest",
        .description = "Run transaction tests: zig build txtest -- <file-or-dir>",
    });

    // ethereum/tests BlockchainTests block RLP through the strict block decoder.
    _ = add_tool(b, uses_base, target, optimize, .{
        .name = "blockrlp",
        .path = "src/common/consensus/block_test_main.zig",
        .step = "blockrlp",
        .description = "Check block RLP: zig build blockrlp -- <file-or-dir>",
    });

    // base/base genesis parity (files from `just vectors`).
    _ = add_tool(b, uses_base, target, optimize, .{
        .name = "genesischeck",
        .path = "src/common/genesis/check_main.zig",
        .step = "genesischeck",
        .description = "Check genesis files: zig build genesischeck -- <genesis.json>...",
    });
    return statetest;
}

const Tool = struct {
    name: []const u8,
    path: []const u8,
    step: []const u8,
    description: []const u8,
};

/// The tools that generate committed tables. Each gets a step that prints its file and a
/// `check:<tool>` step (part of `zig build check`) that fails when the committed file differs
/// from what it prints.
fn add_generators(
    b: *std.Build,
    imports: []const std.Build.Module.Import,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) void {
    // Regenerates the KZG verifier's precomputed pairing lines (src/common/crypto/kzg).
    const kzg_lines = add_tool(b, imports, target, optimize, .{
        .name = "kzg-lines",
        .path = "src/common/crypto/kzg/prepared_lines_main.zig",
        .step = "kzg-lines",
        .description = "Print prepared_lines.zig: zig build kzg-lines > <that file>",
    });
    check_generated(b, kzg_lines, "src/common/crypto/kzg/prepared_lines.zig");

    // Regenerates the secp256k1 generator tables (src/common/crypto/secp256k1).
    const secp_tables = add_tool(b, imports, target, optimize, .{
        .name = "secp-tables",
        .path = "src/common/crypto/secp256k1/table_main.zig",
        .step = "secp-tables",
        .description = "Print table_data.zig: zig build secp-tables > <that file>",
    });
    check_generated(b, secp_tables, "src/common/crypto/secp256k1/table_data.zig");
}

/// `check:<tool>`: a run of `tool --check <path>`, which fails when the committed file differs
/// from the tool's output.
fn check_generated(b: *std.Build, tool: *std.Build.Step.Compile, path: []const u8) void {
    const run = b.addRunArtifact(tool);
    run.setName(b.fmt("check {s}", .{path}));
    run.addArg("--check");
    run.addFileArg(b.path(path));
    run.expectExitCode(0);
    const description = b.fmt("Check {s} against its generator", .{path});
    b.step(b.fmt("check:{s}", .{tool.name}), description).dependOn(&run.step);
}

/// An executable over the given modules with a run step that forwards `-- args`.
fn add_tool(
    b: *std.Build,
    imports: []const std.Build.Module.Import,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    tool: Tool,
) *std.Build.Step.Compile {
    const exe = b.addExecutable(.{
        .name = tool.name,
        .root_module = b.createModule(.{
            .root_source_file = b.path(tool.path),
            .target = target,
            .optimize = optimize,
            .imports = imports,
        }),
    });
    const run = b.addRunArtifact(exe);
    run.addPassthruArgs();
    b.step(tool.step, tool.description).dependOn(&run.step);
    return exe;
}

/// Each binary gets an install and a `run-<name>` step. Its root module is the package
/// `bin/<name>` (packages.zon), so its tests are package tests like any other.
fn add_binaries(b: *std.Build, modules: []const *std.Build.Module, use_llvm: ?bool) void {
    for (binaries) |name| {
        const exe = b.addExecutable(.{
            .name = name,
            .use_llvm = use_llvm,
            .root_module = modules[package_index(b.fmt("bin/{s}", .{name}))],
        });
        b.installArtifact(exe);

        const run = b.addRunArtifact(exe);
        run.addPassthruArgs();
        const run_step = b.step(b.fmt("run-{s}", .{name}), b.fmt("Run {s}", .{name}));
        run_step.dependOn(&run.step);
        if (std.mem.eql(u8, name, "replay-roots")) {
            b.step(name, "Check state/receipts/transactions roots: replay-roots -- DIR [BLOCK]")
                .dependOn(&run.step);
        }
    }
}
